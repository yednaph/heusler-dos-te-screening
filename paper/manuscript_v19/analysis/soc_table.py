#!/usr/bin/env python3
"""Supplementary Table S14: SOC effect by heavy element, from analysis/soc_paired.csv (existing calculations only)."""
import os as _os_htr  # release v1: project paths come from the environment
_HTR = _os_htr.environ.get('HEUSLER_TE_ROOT', _os_htr.path.abspath(_os_htr.path.join(_os_htr.path.dirname(__file__), '../../..')))
_HTE = _os_htr.environ.get('HEUSLER_TE_EXPORT', _os_htr.path.join(_HTR, 'DOS_EXPORT'))
import re
from pathlib import Path
import pandas as pd
HERE = Path(__file__).resolve().parent
BAR = 1.0857214253081801e12                                       # power-factor threshold PF0
p = pd.read_csv(HERE / 'soc_paired.csv')
D = pd.read_pickle(_HTR + '/results/paper_analysis/paper_dataset.pkl')
D = D[D.soc_status == 'done'][['run_dir', 'w1_cap1e21_p_900_PF', 'soc_w1_cap1e21_p_900_PF', 'w1_cap1e21_n_900_PF', 'soc_w1_cap1e21_n_900_PF']]
p = p.merge(D, on='run_dir', how='left')                          # 900 K, |n| <= 1e21 cm^-3, p- and n-type separately
p['rp'] = p.soc_w1_cap1e21_p_900_PF / p.w1_cap1e21_p_900_PF
p['rn'] = p.soc_w1_cap1e21_n_900_PF / p.w1_cap1e21_n_900_PF
el = lambda s: set(re.findall(r'[A-Z][a-z]?', s))
c = p[p.qualified & (p.dft_class == 'gapped')].copy()             # scalar heavy-element candidates
c['lost'] = c.soc_best_PF <= BAR
c['S_ratio'] = c.soc_S_best.abs() / c.S_best.abs(); c['sig_ratio'] = c.soc_sigma_best / c.sigma_best
g = p[(p.dft_class == 'gapped') & (p.soc_class == 'gapped')]
rows = []
for e in ['Hf', 'Ta', 'W', 'Re', 'Os', 'Ir', 'Pt', 'Au', 'Hg', 'Tl', 'Pb', 'Bi']:
    m = p.composition.map(lambda s: e in el(s)); mc = c.composition.map(lambda s: e in el(s))
    mg = g.composition.map(lambda s: e in el(s))
    if not m.sum(): continue
    x = c[mc]
    lost = sorted(set(x[x.lost].composition))
    rows.append([e, int(m.sum()), f'{p[m].pf_ratio.median():.2f}', f'$-${-1e3 * g[mg].dgap.median():.0f}' if mg.sum() else '--',
                 int(mc.sum()), int(x.lost.sum()) if len(x) else 0,
                 f'{x.pf_ratio.median():.2f}' if len(x) else '--', f'{x.S_ratio.median():.2f}' if len(x) else '--',
                 f'{x.sig_ratio.median():.2f}' if len(x) else '--', f'{x.rp.median():.2f}' if len(x) else '--',
                 f'{x.rn.median():.2f}' if len(x) else '--', ', '.join(lost) if lost else '--'])
L = [r'\begin{tabular}{@{}l r r r r r r r r r r >{\raggedright\arraybackslash}p{3.4cm}@{}}', r'\toprule',
     r' & \multicolumn{3}{c}{all paired runs} & \multicolumn{7}{c}{scalar candidates (gapped, qualified)} & \\',
     r'\cmidrule(lr){2-4}\cmidrule(lr){5-11}',
     r'element & runs & PF ratio & $\Delta E_g$ (meV) & runs & lost & PF ratio & $|S|$ ratio & $\sigma/\tau$ ratio & p, 900\,K & n, 900\,K & compositions lost \\', r'\midrule']
L += [' & '.join(map(str, r)) + r' \\' for r in rows]
L += [r'\midrule', f'all & {len(p)} & {p.pf_ratio.median():.2f} & $-${-1e3 * g.dgap.median():.0f} & {len(c)} & {int(c.lost.sum())} & '
      f'{c.pf_ratio.median():.2f} & {c.S_ratio.median():.2f} & {c.sig_ratio.median():.2f} & {c.rp.median():.2f} & {c.rn.median():.2f} & {c[c.lost].composition.nunique()} compositions \\\\',
      r'\bottomrule', r'\end{tabular}']
(HERE.parent / 'tables/si_tab_soc.tex').write_text('% generated by analysis/soc_table.py\n' + '\n'.join(L) + '\n')
print('\n'.join(L))
