def _make_loader(dataset: CIFDataset, batch_size: int) -> DataLoader:
    _nw = 0  # SLURM cpus-per-task=2 cgroup kills worker processes — force single-process
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=_nw,
        pin_memory=False,      # DGL graphs are not pin_memory-safe across DGL versions
        prefetch_factor=None,
        collate_fn=CIFDataset.collate,
    )


@torch.no_grad()
def single_model_predict(
    model: ALIGNN,
    dataset: CIFDataset,
    batch_size: int,
    device: torch.device,
) -> Tuple[np.ndarray, List[str]]:
    """
    Predict d-DOS for all materials in dataset using a single model.

    Returns:
        predictions: np.ndarray (N, 4002), float32
        ids:         list of str material IDs
    """
    loader    = _make_loader(dataset, batch_size)
    all_preds = []
    all_ids   = []
    n_batches = len(loader)
    t0        = time.time()

    for batch_idx, batch in enumerate(loader):
        if batch is None:
            continue

        if batch_idx % 20 == 0:
            elapsed = time.time() - t0
            rate    = len(all_ids) / max(elapsed, 1e-6)
            print(f"  Batch {batch_idx + 1}/{n_batches} | "
                  f"{len(all_ids):,} done | {elapsed:.0f}s | {rate:.1f} mat/s",
                  flush=True)

        g, lg, lat = batch["graph"]
        out_raw    = model((g.to(device), lg.to(device), lat.to(device)))
        out        = F.softplus(out_raw, beta=1)

        all_preds.append(out.cpu().numpy().astype(np.float32))
        all_ids.extend(batch["id"])

    if not all_preds:
        return np.empty((0, 4002), dtype=np.float32), []

    return np.concatenate(all_preds, axis=0), all_ids


@torch.no_grad()
def ensemble_predict(
    checkpoint_paths: List[Path],
    config: dict,
    dataset: CIFDataset,
    batch_size: int,
    device: torch.device,
) -> Tuple[np.ndarray, np.ndarray, List[str]]:
    """
    Predict d-DOS with an ensemble of checkpoints → mean + std.

    Mean prediction is the best estimate; std gives per-energy-point uncertainty
    (used for D35/D36/D37 reliability flags in compute_te_descriptors.py).

    Returns:
        mean_pred: (N, 4002)  — ensemble mean
        std_pred:  (N, 4002)  — ensemble std (uncertainty)
        ids:       list of str
    """
    all_fold_preds: List[np.ndarray] = []
    ids: Optional[List[str]] = None

    for fold_idx, ckpt_path in enumerate(checkpoint_paths):
        print(f"\n  Fold {fold_idx + 1}/{len(checkpoint_paths)}: {ckpt_path}")
        model            = load_model(Path(ckpt_path), config, device)
        preds, fold_ids  = single_model_predict(model, dataset, batch_size, device)
        all_fold_preds.append(preds)
        if ids is None:
            ids = fold_ids
        del model
        if device.type == "cuda":
            torch.cuda.empty_cache()

    # Verify all folds produced predictions for the same set of materials
    n_per_fold = [p.shape[0] for p in all_fold_preds]
    if len(set(n_per_fold)) > 1:
        raise RuntimeError(
            f"Ensemble fold predictions have inconsistent sizes: {n_per_fold}. "
            f"Some folds failed on different CIFs. Check graph-build warnings above."
        )

    stacked   = np.stack(all_fold_preds, axis=0)   # (n_folds, N, 4002)
    mean_pred = stacked.mean(axis=0)               # (N, 4002)
    std_pred  = stacked.std(axis=0)                # (N, 4002)
    return mean_pred, std_pred, ids or []


