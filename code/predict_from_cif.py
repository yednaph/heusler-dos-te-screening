def main():
    parser = argparse.ArgumentParser(
        description="Predict d-projected DOS for novel CIF files (no ground-truth DOS).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--cif_dir",    required=True,  type=Path,
                        help="Directory of prediction CIF files (e.g. data/predictions/full_cubic)")
    parser.add_argument("--config",     required=True,  type=Path,
                        help="Merged per-fold config YAML from output/{dataset}/{exp}/fold0/")
    parser.add_argument("--output_dir", required=True,  type=Path,
                        help="Output directory for predictions.npy, ids.txt, etc.")
    parser.add_argument("--dataset",    required=True,
                        help="Dataset name for logging (e.g. full_cubic)")
    parser.add_argument("--checkpoint", type=Path, default=None,
                        help="Single checkpoint (swa_model.pt or best.pt) for single-model inference")
    parser.add_argument("--ensemble_checkpoints", nargs="+", type=str, default=None,
                        help="Space-separated checkpoint paths for ensemble inference")
    parser.add_argument("--batch_size",    type=int,   default=256,
                        help="Inference batch size (default 256; increase to 512 on H100)")
    parser.add_argument("--cutoff",        type=float, default=8.0,
                        help="Graph edge cutoff in Angstroms (default 8.0, must match training)")
    parser.add_argument("--max_neighbors", type=int,   default=12,
                        help="Max neighbours per atom in graph (default 12, must match training)")
    args = parser.parse_args()

    # ── Validate ──────────────────────────────────────────────────────────────
    if args.checkpoint is None and args.ensemble_checkpoints is None:
        parser.error("Provide --checkpoint (single model) or --ensemble_checkpoints (ensemble)")
    if not args.cif_dir.exists():
        print(f"ERROR: cif_dir not found: {args.cif_dir}"); sys.exit(1)
    if not args.config.exists():
        print(f"ERROR: config not found: {args.config}"); sys.exit(1)

    args.output_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 62)
    print("ALIGNN Prediction from CIF files")
    print("=" * 62)
    print(f"Dataset   : {args.dataset}")
    print(f"CIF dir   : {args.cif_dir}")
    print(f"Output    : {args.output_dir}")
    mode = "ensemble" if args.ensemble_checkpoints else "single"
    print(f"Mode      : {mode}")

    # ── Device ────────────────────────────────────────────────────────────────
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device    : {device}")
    if device.type == "cuda":
        print(f"GPU       : {torch.cuda.get_device_name(0)}")

    # ── Config ────────────────────────────────────────────────────────────────
    with open(args.config) as f:
        config = yaml.safe_load(f)

    # ── Dataset ───────────────────────────────────────────────────────────────
    print(f"\nBuilding CIFDataset ...")
    dataset = CIFDataset(
        cif_dir=args.cif_dir,
        cutoff=args.cutoff,
        max_neighbors=args.max_neighbors,
    )
    N_total = len(dataset)

    if N_total == 0:
        print("ERROR: No CIF files found in", args.cif_dir)
        sys.exit(1)

    t_start = time.time()
    std_pred = None

    # ── Inference ─────────────────────────────────────────────────────────────
    if args.ensemble_checkpoints:
        ckpt_paths = [Path(p) for p in args.ensemble_checkpoints]
        for p in ckpt_paths:
            if not p.exists():
                print(f"ERROR: checkpoint not found: {p}"); sys.exit(1)
        print(f"\nRunning ENSEMBLE inference ({len(ckpt_paths)} checkpoints)...")
        mean_pred, std_pred, ids = ensemble_predict(
            ckpt_paths, config, dataset, args.batch_size, device
        )
        predictions = mean_pred
    else:
        if not args.checkpoint.exists():
            print(f"ERROR: checkpoint not found: {args.checkpoint}"); sys.exit(1)
        print(f"\nLoading model: {args.checkpoint}")
        model = load_model(args.checkpoint, config, device)
        print(f"\nRunning inference (batch_size={args.batch_size})...")
        predictions, ids = single_model_predict(model, dataset, args.batch_size, device)

    t_elapsed = time.time() - t_start
    N_done    = len(ids)
    N_failed  = N_total - N_done

    # ── Sanity checks ─────────────────────────────────────────────────────────
    if N_done > 0:
        assert predictions.shape == (N_done, 4002), \
            f"Unexpected predictions shape: {predictions.shape}"
        assert (predictions >= 0).all(), \
            "Negative DOS values after softplus — unexpected"
        n_bad = int(np.sum(~np.isfinite(predictions)))
        if n_bad > 0:
            print(f"  WARNING: {n_bad} NaN/Inf values detected in predictions — check model/input")

    # ── Save outputs ──────────────────────────────────────────────────────────
    pred_path    = args.output_dir / "predictions.npy"
    ids_path     = args.output_dir / "ids.txt"
    summary_path = args.output_dir / "screening_summary.txt"

    np.save(pred_path, predictions)
    with open(ids_path, "w") as f:
        for mid in ids:
            f.write(f"{mid}\n")

    if std_pred is not None:
        std_path = args.output_dir / "predictions_std.npy"
        np.save(std_path, std_pred)

    # Write summary
    throughput = N_done / max(t_elapsed, 1e-6)
    with open(summary_path, "w") as f:
        f.write(f"dataset          : {args.dataset}\n")
        f.write(f"mode             : {mode}\n")
        f.write(f"cif_dir          : {args.cif_dir}\n")
        f.write(f"N_total_cifs     : {N_total}\n")
        f.write(f"N_predicted      : {N_done}\n")
        f.write(f"N_failed         : {N_failed}\n")
        f.write(f"elapsed_s        : {t_elapsed:.1f}\n")
        f.write(f"throughput_mat_s : {throughput:.1f}\n")
        if args.checkpoint:
            f.write(f"checkpoint       : {args.checkpoint}\n")
        elif args.ensemble_checkpoints:
            for i, c in enumerate(args.ensemble_checkpoints):
                f.write(f"checkpoint_{i}     : {c}\n")

    # ── Summary printout ──────────────────────────────────────────────────────
    print(f"\n{'=' * 62}")
    print(f"Screening complete")
    print(f"  N predicted : {N_done:,} / {N_total:,}")
    if N_failed > 0:
        print(f"  N failed    : {N_failed:,}  (CIF parse or graph build errors)")
    print(f"  Elapsed     : {t_elapsed:.1f}s  ({t_elapsed / 60:.1f} min)")
    print(f"  Throughput  : {throughput:.1f} materials/s")
    print(f"\nSaved to {args.output_dir}/")
    print(f"  predictions.npy     {pred_path.stat().st_size / 1e6:.1f} MB")
