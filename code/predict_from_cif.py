#!/usr/bin/env python3
"""
predict_from_cif.py — ALIGNN d-projected DOS inference on novel CIF files.

This is the production screening pipeline for the 54,978 DxMag prediction CIFs
generated by generate_prediction_cifs_from_dxmag.py.

Unlike run_inference.py, this script:
  - Reads structure from CIF files (no DOS JSON — no ground truth for novel materials)
  - Uses a custom CIF parser that bypasses pymatgen symmetry expansion
    (our CIFs carry the original DxMag space group but store explicit primitive-cell
    atom positions — applying Fm-3m / I4/mmm symmetry would wrongly expand them)
  - Outputs predictions.npy + ids.txt (no targets.npy)
  - Supports ensemble inference (multiple checkpoints → mean + std)
  - Feeds directly into compute_te_descriptors.py for D34 TE screening

Usage (single model):
    python code/predict_from_cif.py \\
        --cif_dir     data/predictions/full_cubic \\
        --checkpoint  output/full_cubic/expC/fold0/checkpoints/swa_model.pt \\
        --config      output/full_cubic/expC/fold0/config_expC_fold0.yaml \\
        --output_dir  results/screening/full_cubic/expC/ \\
        --dataset     full_cubic

Usage (ensemble — 2 fold models for uncertainty):
    python code/predict_from_cif.py \\
        --cif_dir     data/predictions/full_cubic \\
        --config      output/full_cubic/expA/fold0/config_expA_fold0.yaml \\
        --output_dir  results/screening/full_cubic/expA_ensemble/ \\
        --dataset     full_cubic \\
        --ensemble_checkpoints \\
            output/full_cubic/expA/fold0/checkpoints/swa_model.pt \\
            output/full_cubic/expA/fold1/checkpoints/swa_model.pt

Outputs (in --output_dir):
    predictions.npy          float32 (N, 4002)   predicted d-projected DOS
    ids.txt                  one material_id per line (CIF file stems)
    predictions_std.npy      float32 (N, 4002)   ensemble std (ensemble mode only)
    screening_summary.txt    N processed, N failed, timing info

Next step — TE screening (pass predictions as targets since no ground truth):
    python code/compute_te_descriptors.py \\
        --predictions results/screening/full_cubic/expC/predictions.npy \\
        --targets     results/screening/full_cubic/expC/predictions.npy \\
        --ids         results/screening/full_cubic/expC/ids.txt \\
        --dataset     full_cubic --experiment C --fold 0 \\
        --output_dir  results/screening/full_cubic/expC/
"""

