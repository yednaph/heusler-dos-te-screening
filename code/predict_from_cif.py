# ---------------------------------------------------------------------------
# Custom CIF reader
# ---------------------------------------------------------------------------
# Our generated CIFs (from generate_prediction_cifs_from_dxmag.py) carry the
# original DxMag space group (e.g. 'Fm-3m', 'I4/mmm') but list PRIMITIVE-CELL
# atom positions explicitly. Pymatgen's CifParser would apply the full space
# group symmetry to those positions, expanding 4 atoms → up to 16 (wrong).
#
# Solution: parse the CIF text directly, read cell parameters and explicit atom
# positions, and construct a Structure in P1. This is safe because all atoms
# are listed explicitly (no asymmetric-unit shorthand) and we control the format.
# ---------------------------------------------------------------------------

def _read_structure_from_generated_cif(cif_path: Path) -> Structure:
    """
    Parse a CIF generated by generate_prediction_cifs_from_dxmag.py and return
    a pymatgen Structure in P1 (no symmetry expansion applied).

    CIF format written by write_cif():
        _cell_length_a    a
        _cell_length_b    b
        _cell_length_c    c
        _cell_angle_alpha alpha
        _cell_angle_beta  beta
        _cell_angle_gamma gamma
        _symmetry_space_group_name_H-M '...'    <- ignored here, we use P1
        loop_
        _atom_site_label
        _atom_site_type_symbol
        _atom_site_fract_x
        _atom_site_fract_y
        _atom_site_fract_z
        El1   El   x.xxxxxx   y.yyyyyy   z.zzzzzz
        ...

    Raises:
        ValueError: if required fields are missing or atom positions cannot be parsed
    """
    text = cif_path.read_text(errors='replace')

    def _get(key: str) -> Optional[str]:
        # (?!\w) prevents '_cell_angle_alpha' from matching '_cell_angle_alpha_suffix'
        m = re.search(rf'{re.escape(key)}(?!\w)\s*([\S]+)', text)
        return m.group(1).strip("'\"") if m else None

    try:
        a  = float(_get('_cell_length_a')  or 0)
        b  = float(_get('_cell_length_b')  or 0)
        c  = float(_get('_cell_length_c')  or 0)
        al = float(_get('_cell_angle_alpha') or 0)
        be = float(_get('_cell_angle_beta')  or 0)
        ga = float(_get('_cell_angle_gamma') or 0)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"Cannot parse cell parameters from {cif_path.name}: {exc}") from exc

    if a <= 0 or b <= 0 or c <= 0:
        raise ValueError(f"Invalid cell lengths a={a} b={b} c={c} in {cif_path.name}")

    lattice = Lattice.from_parameters(a, b, c, al, be, ga)

    # Parse atom site loop — format: label  element  x  y  z
    # Float pattern supports fixed decimal (0.250000) and scientific notation (1.23e-08).
    _F = r'[-+]?(?:\d+\.?\d*|\d*\.\d+)(?:[eE][-+]?\d+)?'
    atom_rows = re.findall(
        rf'^\s*\w+\s+([A-Za-z]{{1,2}})\s+({_F})\s+({_F})\s+({_F})',
        text, re.M
    )

    if not atom_rows:
        raise ValueError(f"No atom positions found in {cif_path.name}")

    species = [r[0] for r in atom_rows]
    coords  = [[float(r[1]), float(r[2]), float(r[3])] for r in atom_rows]

    # Build P1 structure directly — no symmetry expansion
    return Structure(lattice, species, coords)


# ---------------------------------------------------------------------------
# CIFDataset
# ---------------------------------------------------------------------------

class CIFDataset(Dataset):
    """
    PyTorch Dataset for ALIGNN inference from CIF files (no ground-truth DOS).

    Graph construction is identical to DOSDataset:
      CIF → pymatgen Structure (P1) → jarvis Atoms → _build_graph()
      → atom_graph + line_graph with 5 Heusler-specific node features (97 total)

    Returns None for samples that fail to parse (handled by collate).
    """

    def __init__(
        self,
        cif_dir: Path,
        ids: Optional[List[str]] = None,
        cutoff: float = 8.0,
        max_neighbors: int = 12,
    ):
        """
        Args:
            cif_dir:       Directory containing CIF files
            ids:           Optional explicit list of CIF stems. If None, all
                           *.cif files in cif_dir are used (sorted).
            cutoff:        Graph edge cutoff in Angstroms (must match training, default 8.0)
            max_neighbors: Max neighbours per atom (must match training, default 12)
        """
        self.cif_dir       = Path(cif_dir)
        self.cutoff        = cutoff
        self.max_neighbors = max_neighbors

        if ids is not None:
            self.ids = []
            missing = []
            for mid in ids:
                if (self.cif_dir / f"{mid}.cif").exists():
                    self.ids.append(mid)
                else:
                    missing.append(mid)
            if missing:
                print(f"WARNING: {len(missing)} CIF files not found:")
                for m in missing[:5]:
                    print(f"  {m}.cif")
                if len(missing) > 5:
                    print(f"  ... and {len(missing) - 5} more")
        else:
            self.ids = sorted(p.stem for p in self.cif_dir.glob("*.cif"))

        print(f"CIFDataset: {len(self.ids):,} CIF files in {cif_dir}")

    def __len__(self) -> int:
        return len(self.ids)

    def __getitem__(self, idx: int):
        mid      = self.ids[idx]
        cif_path = self.cif_dir / f"{mid}.cif"

        # Parse structure from CIF (custom P1 reader — no symmetry expansion)
        try:
            structure = _read_structure_from_generated_cif(cif_path)
        except Exception as exc:
            print(f"[WARNING] {mid}: CIF parse failed — {exc}", flush=True)
            return None

        # Convert to jarvis Atoms
        try:
            atoms = pmg_to_atoms(structure)
        except Exception as exc:
            print(f"[WARNING] {mid}: pmg_to_atoms failed — {exc}", flush=True)
            return None

        # Build ALIGNN graph (identical to DOSDataset._build_graph)
        try:
            g, lg, lattice = _build_graph(atoms, self.cutoff, self.max_neighbors)
        except Exception as exc:
            print(f"[WARNING] {mid}: graph build failed — {exc}", flush=True)
            return None

        return {
            "graph": (g, lg, lattice),   # 3-tuple; ALIGNN.forward() unpacks g, lg, lat = graph
            "id":    mid,
        }

    @staticmethod
    def collate(batch: list):
        """
        Custom collate — mirrors DOSDataset.collate but without DOS target.
        Filters None entries (failed CIF reads / graph builds).
        Returns None if every sample in the batch failed.
        """
        valid = [b for b in batch if b is not None]
        n_skip = len(batch) - len(valid)
        if n_skip > 0:
            print(f"[WARNING] collate: {n_skip}/{len(batch)} samples skipped", flush=True)
        if not valid:
            return None

        return {
            "graph": (
                dgl.batch([b["graph"][0] for b in valid]),
                dgl.batch([b["graph"][1] for b in valid]),
                torch.stack([b["graph"][2] for b in valid]),  # (N, 3, 3)
            ),
            "id": [b["id"] for b in valid],
        }


# ---------------------------------------------------------------------------
# Model loading (identical to run_inference.py)
# ---------------------------------------------------------------------------

def load_model(checkpoint_path: Path, config: dict, device: torch.device) -> ALIGNN:
    """
    Load ALIGNN from checkpoint. Must mirror create_model() in train_hpc.py exactly.

    Architecture:
      - Base ALIGNN encoder: alignn_layers=8, gcn_layers=8, hidden_dim=512, atom_input_features=97
      - Deep output head (deep_output_head=true in config):
          nn.Sequential(Linear(512,1024), GELU, Dropout, Linear(1024,2048), GELU, Dropout, Linear(2048,4002))
          Keys in state dict: fc.0.weight, fc.3.weight, fc.6.weight

    Handles 3 checkpoint formats:
      1. dict with 'model_state_dict'  (standard train_hpc.py checkpoint)
      2. dict with 'model_state'        (legacy format)
      3. raw state_dict                 (best_fermi.pt, swa_model.pt)
    """
    model_config = config["model"]

    # Step 1: Build base ALIGNN encoder
    alignn_cfg = ALIGNNConfig(
        name="alignn",
        alignn_layers=model_config["alignn_layers"],
        gcn_layers=model_config["gcn_layers"],
        hidden_features=model_config["hidden_dim"],
        output_features=model_config["output_dim"],
        atom_input_features=model_config.get("atom_input_features", 97),
    )
    model = ALIGNN(alignn_cfg)

    # Step 2: Replace output head with deep MLP — MUST match train_hpc.py create_model()
    # Base ALIGNN has model.fc = Linear(hidden, output_dim) — single layer.
    # Checkpoints were saved with deep MLP head (fc.0/fc.3/fc.6 keys).
    # Without this replacement, load_state_dict crashes: unexpected key 'fc.0.weight'.
    hidden    = model_config["hidden_dim"]       # 512
    dropout_p = model_config.get("dropout", 0.2)
    if model_config.get("deep_output_head", True):
        model.fc = nn.Sequential(
            nn.Linear(hidden, hidden * 2),       # fc.0  (1024, 512)
            nn.GELU(),                           # fc.1
            nn.Dropout(dropout_p),               # fc.2
            nn.Linear(hidden * 2, hidden * 4),   # fc.3  (2048, 1024)
            nn.GELU(),                           # fc.4
            nn.Dropout(dropout_p),               # fc.5
            nn.Linear(hidden * 4, 4002),         # fc.6  (4002, 2048)
        )

    model = model.to(device)

    # Step 3: Load weights
    # Checkpoint format depends on file:
    #   best_fermi.pt, swa_model.pt  → raw state_dict  (torch.save(model.state_dict(), path))
    #   best.pt, last.pt             → checkpoint dict  (has 'model_state_dict' key)
    checkpoint = torch.load(checkpoint_path, map_location=device, weights_only=False)
    if isinstance(checkpoint, dict):
        if "model_state_dict" in checkpoint:
            state_dict = checkpoint["model_state_dict"]
        elif "model_state" in checkpoint:
            state_dict = checkpoint["model_state"]
        else:
            # Raw state dict (best_fermi.pt / swa_model.pt)
            state_dict = checkpoint
    else:
        state_dict = checkpoint

    missing, unexpected = model.load_state_dict(state_dict, strict=True)
    if missing:
        raise RuntimeError(f"Missing keys in checkpoint {checkpoint_path.name}: {missing[:5]}")
    if unexpected:
        raise RuntimeError(f"Unexpected keys in checkpoint {checkpoint_path.name}: {unexpected[:5]}")

    model.eval()

    n_params = sum(p.numel() for p in model.parameters())
    print(f"  Loaded: {checkpoint_path.name}  ({n_params:,} params)  device={device}")
    if isinstance(checkpoint, dict) and "epoch" in checkpoint:
        print(f"  Checkpoint epoch: {checkpoint['epoch']}")

    return model


