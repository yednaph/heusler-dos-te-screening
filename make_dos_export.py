def verify_load(c: Collector, ckpt_records):
    try:
        import torch
    except ImportError:
        print("  [verify] torch not importable — skipping strict-load verification")
        return {}
    info = {}
    for rec in ckpt_records:
        if not rec["present"]:
            continue
        p = c.out / rec["dest"]
        try:
            sd = torch.load(p, map_location="cpu", weights_only=False)
            if isinstance(sd, dict) and "model_state_dict" in sd:
                fmt, sd = "wrapped:model_state_dict", sd["model_state_dict"]
            else:
                fmt = "raw_state_dict"
            n_params = sum(v.numel() for v in sd.values() if hasattr(v, "numel"))
            head = [k for k in sd if k.endswith("fc.6.weight")]
            head_shape = list(sd[head[0]].shape) if head else None
            emb = [k for k in sd if "atom_embedding" in k and k.endswith("weight")]
            emb_in = (sd[emb[0]].shape[-1] if emb else None)
            dtypes = {str(v.dtype) for v in sd.values() if hasattr(v, "dtype")}
            info[rec["dest"]] = {"format": fmt, "n_params": int(n_params),
                                 "head_out_shape": head_shape,
                                 "atom_embedding_in_dim": int(emb_in) if emb_in else None,
                                 "dtypes": sorted(dtypes)}
            ok = (head_shape and head_shape[0] == 4002)
            print(f"  [verify] {rec['dest']}: {fmt}, {n_params/1e6:.1f}M params, "
                  f"head->{head_shape}, emb_in={emb_in} {'OK' if ok else '!! UNEXPECTED'}")
            del sd
        except Exception as e:
            info[rec["dest"]] = {"error": str(e)}
            c.missing.append({"item": rec["dest"], "expected_source": rec["source"],
                              "severity": "REQUIRED", "note": f"verification load failed: {e}"})
    return info


