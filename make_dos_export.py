def make_zip(c: Collector, zip_path: Path):
    print(f"[zip] writing {zip_path} ...")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=1,
                         allowZip64=True) as zf:
        for f in sorted(c.out.rglob("*")):
            if f.is_file():
                zf.write(f, arcname=str(Path(c.out.name) / f.relative_to(c.out)))
    return zip_path.stat().st_size


