def collect_checkpoints(c: Collector, include_best_fermi: bool):
    records = []
    for fam in FAMILIES:
        for fold in FOLDS:
            src = c.root / "output" / fam / f"exp{EXP}" / f"fold{fold}" / "checkpoints" / "swa_model.pt"
            dest_rel = f"checkpoints/{fam}/fold{fold}/swa_model.pt"
            ok = c.copy(src, dest_rel,
                        f"Production checkpoint: {fam} ensemble member fold {fold} (SWA-averaged, BN-updated)")
            records.append({"family": fam, "fold": fold, "dest": dest_rel,
                            "present": ok, "source": str(src)})
            if include_best_fermi:
                c.copy(src.parent / "best_fermi.pt",
                       f"checkpoints/{fam}/fold{fold}/best_fermi.pt",
                       f"Secondary checkpoint: {fam} fold {fold} pre-SWA best-Fermi-Pearson epoch",
                       severity="OPTIONAL")
    return records


