def capture_environment(c: Collector):
    envdir = self_out = c.out / "environment"
    envdir.mkdir(parents=True, exist_ok=True)

    def run(cmd, outfile, shell=False):
        try:
            r = subprocess.run(cmd, shell=shell, capture_output=True, text=True, timeout=300)
            (envdir / outfile).write_text(r.stdout + (("\n[stderr]\n" + r.stderr) if r.stderr.strip() else ""))
            c.inventory.append({"dest": f"environment/{outfile}", "source": "(captured at export time)",
                                "purpose": "Environment reproducibility (§3.10)"})
            return r.stdout.strip()
        except Exception as e:
            (envdir / outfile).write_text(f"CAPTURE FAILED: {e}\n")
            c.missing.append({"item": f"environment/{outfile}", "expected_source": str(cmd),
                              "severity": "IMPORTANT", "note": f"capture failed: {e}"})
            return ""

    run([sys.executable, "-m", "pip", "freeze"], "pip_freeze.txt")
    run("conda env export 2>/dev/null || echo 'conda not available'", "conda_environment.yml", shell=True)
    run("nvidia-smi 2>/dev/null || echo 'no GPU visible'", "nvidia_smi.txt", shell=True)
    run("nvcc --version 2>/dev/null || echo 'nvcc not on PATH'", "nvcc_version.txt", shell=True)
    run("cat /etc/os-release; uname -a", "os_info.txt", shell=True)

    versions = {"python": platform.python_version(),
                "platform": platform.platform(),
                "captured_utc": datetime.now(timezone.utc).isoformat(),
                "conda_env": os.environ.get("CONDA_DEFAULT_ENV", "(none)")}
    for mod in ("torch", "dgl", "alignn", "pymatgen", "jarvis", "numpy", "scipy"):
        try:
            m = __import__(mod)
            versions[mod] = getattr(m, "__version__", "unknown")
            if mod == "torch":
                versions["torch_cuda"] = getattr(m.version, "cuda", None)
                versions["cudnn"] = (m.backends.cudnn.version()
                                     if m.backends.cudnn.is_available() else None)
        except Exception as e:
            versions[mod] = f"IMPORT FAILED: {e}"
    c.write("environment/key_versions.json", json.dumps(versions, indent=2),
            "Key package versions (torch/dgl/alignn are load-bearing for graph construction)")
    return versions


def generate_golden(c: Collector, n_per_family: int):
    """Run the real pipeline (run_inference.py) with fold-0 swa weights on a few
    held-out materials per family; also slice the original best.pt dumps."""
    try:
        import numpy as np
    except ImportError:
        c.missing.append({"item": "runtime_assets/golden_pairs/*", "expected_source": "numpy",
                          "severity": "IMPORTANT", "note": "numpy not importable — golden generation skipped"})
        return
    import tempfile

    for fam in FAMILIES:
        rdir = results_fold_dir(c.root, fam, 0)
        ids_file = rdir / "test_ids.txt"
        ckpt = c.root / "output" / fam / f"exp{EXP}" / "fold0" / "checkpoints" / "swa_model.pt"
        cfg = c.root / "output" / fam / f"exp{EXP}" / "fold0" / f"config_exp{EXP}_fold0.yaml"
        if not (ids_file.is_file() and ckpt.is_file() and cfg.is_file()):
            c.missing.append({"item": f"runtime_assets/golden_pairs/{fam}",
                              "expected_source": f"{ids_file} + {ckpt} + {cfg}",
                              "severity": "IMPORTANT",
                              "note": "fold0 dump/checkpoint/config missing — golden pair skipped"})
            continue
        ids = [l.strip() for l in ids_file.read_text().splitlines() if l.strip()][:n_per_family]

        gdir = c.out / "runtime_assets" / "golden_pairs" / fam
        (gdir / "inputs").mkdir(parents=True, exist_ok=True)
        kept = []
        for mid in ids:
            src_json = c.root / "data" / fam / "dos_json" / f"{mid}.json"
            if src_json.is_file():
                shutil.copy2(src_json, gdir / "inputs" / f"{mid}.json")
                kept.append(mid)
        if not kept:
            c.missing.append({"item": f"runtime_assets/golden_pairs/{fam}/inputs",
                              "expected_source": f"data/{fam}/dos_json/",
                              "severity": "IMPORTANT", "note": "no input JSONs found"})
            continue

        # secondary reference: slice original best.pt dumps for these ids
        try:
            all_ids = [l.strip() for l in ids_file.read_text().splitlines() if l.strip()]
            preds = np.load(rdir / "test_predictions.npy", mmap_mode="r")
            targs = np.load(rdir / "test_targets.npy", mmap_mode="r")
            rows = [all_ids.index(m) for m in kept]
            bdir = gdir / "bestpt_reference"
            bdir.mkdir(exist_ok=True)
            np.save(bdir / "predictions.npy", np.asarray(preds[rows], dtype=np.float32))
            np.save(bdir / "targets.npy", np.asarray(targs[rows], dtype=np.float32))
            (bdir / "ids.txt").write_text("\n".join(kept) + "\n")
        except Exception as e:
            print(f"  [golden] {fam}: best.pt slice failed ({e}) — continuing")

        # primary golden: run the real pipeline with swa fold0
        with tempfile.NamedTemporaryFile("w", suffix=".csv", delete=False) as tf:
            tf.write("material_id\n" + "\n".join(kept) + "\n")
            tiny_csv = tf.name
        outdir = gdir / "swa_fold0"
        outdir.mkdir(exist_ok=True)
        cmd = [sys.executable, str(c.root / "code" / "run_inference.py"),
               "--checkpoint", str(ckpt), "--config", str(cfg),
               "--test_file", tiny_csv, "--output_dir", str(outdir),
               "--batch_size", "4"]
        print(f"  [golden] {fam}: running swa fold0 on {len(kept)} structures ...")
        r = subprocess.run(cmd, cwd=str(c.root), capture_output=True, text=True)
        (outdir / "run_log.txt").write_text(r.stdout[-8000:] + "\n[stderr]\n" + r.stderr[-8000:])
        os.unlink(tiny_csv)
        if r.returncode != 0 or not (outdir / "test_predictions.npy").is_file():
            c.missing.append({"item": f"runtime_assets/golden_pairs/{fam}/swa_fold0",
                              "expected_source": "code/run_inference.py (swa fold0)",
                              "severity": "IMPORTANT",
                              "note": f"golden inference failed rc={r.returncode}; see run_log.txt"})
        else:
            for fn in ("test_predictions.npy", "test_targets.npy", "test_ids.txt"):
                c.inventory.append({"dest": f"runtime_assets/golden_pairs/{fam}/swa_fold0/{fn}",
                                    "source": "(generated: run_inference.py + swa fold0)",
                                    "purpose": f"GOLDEN reference outputs for {fam} (§3.9)"})
        for mid in kept:
            c.inventory.append({"dest": f"runtime_assets/golden_pairs/{fam}/inputs/{mid}.json",
                                "source": f"data/{fam}/dos_json/{mid}.json",
                                "purpose": f"GOLDEN reference input for {fam} (§3.9)"})


