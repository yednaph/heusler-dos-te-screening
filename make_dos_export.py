def sha256_of(path: Path, buf: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(buf)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


class Collector:
    def __init__(self, root: Path, out: Path):
        self.root = root
        self.out = out
        self.inventory = []   # dicts: dest, source, purpose
        self.missing = []     # dicts: item, expected_source, severity, note

    def copy(self, src, dest_rel: str, purpose: str, severity: str = "REQUIRED",
             note: str = "") -> bool:
        src = Path(src)
        if not src.is_absolute():
            src = self.root / src
        dest = self.out / dest_rel
        if src.is_file():
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest)
            self.inventory.append({
                "dest": dest_rel,
                "source": str(src.relative_to(self.root)) if str(src).startswith(str(self.root)) else str(src),
                "purpose": purpose,
            })
            return True
        self.missing.append({"item": dest_rel, "expected_source": str(src),
                             "severity": severity, "note": note})
        return False

    def write(self, dest_rel: str, text: str, purpose: str):
        dest = self.out / dest_rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)
        self.inventory.append({"dest": dest_rel, "source": "(generated by make_dos_export.py)",
                               "purpose": purpose})


def results_fold_dir(root: Path, fam: str, fold: int) -> Path:
    """Fold results dir; tolerate the doubly-nested local mirror layout."""
